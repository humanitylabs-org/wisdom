"""Deterministic shell identity. Run after changing any served shell byte."""
import hashlib
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
FILES = ['index.html','app.js','wisdom.js','base.css','wisdom.css','collections.css','app.css',
         'manage.js','manage.css','discussions.js','discussions.css','wizard-appearance.js','wizard-appearance.css',
         'icon.svg','icon-192.png','icon-512.png','manifest.webmanifest','offline-kit.js','offline-sw.js','offline.js',
         'wizard-tokens.css','wizard-ui.css','wizard-sheet.js']
SHARED = ['/wizard-os-home/core/app-client.js','/wizard-os-home/core/app-identity.js']

def config():
    h=hashlib.sha256()
    for name in sorted(FILES):
        h.update(name.encode()+b'\0'+(ROOT/'static'/name).read_bytes()+b'\0')
    shared=json.loads((ROOT/'qa/offline-shared-shell.json').read_text())
    for name in sorted(SHARED):h.update(name.encode()+b'\0'+shared[name].encode()+b'\0')
    return dict(prefix='wisdom-',version=h.hexdigest()[:20],shell=['./',*FILES,*SHARED],data=['api/wisdom'],assets=['wisdom-art/'],
                onlineOnly=['api/lookup','api/discussions','api/wisdom/request','api/wisdom/dives','api/library','api/authoring'])

def worker():
    return '/* Generated by tools/offline_shell.py; never force-reloads a client. */\nself.WIZ_OFFLINE_CONFIG = '+json.dumps(config(),sort_keys=True,indent=2)+';\nimportScripts("./offline-sw.js");\n'

if __name__=='__main__':
    (ROOT/'static/sw.js').write_text(worker())
    print(config()['version'])
